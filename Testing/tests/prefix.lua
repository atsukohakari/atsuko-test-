local Prefix = loadmodule("Hub/modules/prefix.lua")

local function lookupOf(list)
	local set = {}
	for _, w in ipairs(list) do
		set[w] = true
	end
	return function(word)
		if set[word] then
			return true
		end
		if string.sub(word, 1, 2) == "un" and set[string.sub(word, 3)] then
			return true
		end
		return false
	end
end

local known = lookupOf({ "fly", "speed", "noclip", "tp", "reload", "esp", "invisible", "visible" })

T.section("prefix: allowed symbols")
local allowed = { ";", ":", "!", ".", ",", "?", "-", "+", "=", "~", "^", "*", "$", "%", "&", ">", "<", "|", "'", "\"", "[", "]", "{", "}", "(", ")", "_", "@", "#" }
for _, ch in ipairs(allowed) do
	local ok, v = Prefix.validate(ch)
	T.eq(ok, true, "accepts " .. ch)
	T.eq(v, ch)
	T.eq(Prefix.allowed(ch), true)
end
T.eq(#allowed, 29)
T.eq(#Prefix.ALLOWED, 29)

T.section("prefix: rejected input")
local bad = { "", " ", "a", "Z", "5", "0", "/", "ab", ";;", "; ", "é", "\226\152\133", "\t", "abc", "..", "ñ", "\226\152\133" }
for _, text in ipairs(bad) do
	local ok, reason = Prefix.validate(text)
	if text == " " or text == "\t" or text == "" then
		T.eq(ok, false, "empty-ish " .. string.format("%q", text))
	elseif text == "; " then
		T.eq(ok, true, "trailing space is trimmed")
	else
		T.eq(ok, false, "rejects " .. string.format("%q", text))
		T.eq(type(reason), "string")
	end
end
T.eq(select(2, Prefix.validate("/")), "/ is Roblox's own command key")
T.eq(select(2, Prefix.validate("a")), "Pick a symbol, not a letter or a number")
T.eq(select(2, Prefix.validate("")), "Type one symbol")
T.eq(select(2, Prefix.validate("ab")), "One symbol only")
T.eq(Prefix.validate(nil), false)
T.eq(Prefix.validate(42), false)
T.eq(Prefix.validate({}), false)
T.eq(select(2, Prefix.validate("  !  ")), "!")
T.eq(Prefix.allowed(nil), false)
T.eq(Prefix.allowed(""), false)
T.eq(Prefix.allowed("a"), false)
T.eq(Prefix.allowed(";;"), false)

