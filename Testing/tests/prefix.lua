local function layoutOf(typedMap, shiftedMap, codes)
	return {
		codes = codes,
		typed = function(name)
			return typedMap[name]
		end,
		shifted = function(name)
			return shiftedMap[name]
		end,
	}
end

local codes = { "Semicolon", "Quote", "Comma", "Period", "Slash", "BackSlash", "Minus", "Equals", "LeftBracket", "RightBracket", "Backquote", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine", "Zero" }

local US = layoutOf(Prefix.KEY_CHARS, Prefix.SHIFTED, codes)

local azertyTyped = { Semicolon = "m", Comma = ";", Period = ":", Slash = "!", Minus = ")", Equals = "=", Quote = "\u{f9}", LeftBracket = "^", RightBracket = "$", BackSlash = "*", Backquote = "\u{b2}" }
local azertyShifted = { Comma = "?", Period = "/", Slash = "\u{a7}", One = "1", Two = "2", Three = "3", Four = "4", Five = "5", Six = "6", Seven = "7", Eight = "8", Nine = "9", Zero = "0", Equals = "+", Minus = "\u{b0}" }
local AZERTY = layoutOf(azertyTyped, azertyShifted, codes)

local qwertzTyped = { Comma = ",", Period = ".", Slash = "-", Minus = "\u{df}", Equals = "'", LeftBracket = "\u{fc}", RightBracket = "+", BackSlash = "#", Semicolon = "\u{f6}", Quote = "\u{e4}", Backquote = "^" }
local qwertzShifted = { Comma = ";", Period = ":", Slash = "_", Minus = "?", Equals = "`", RightBracket = "*", BackSlash = "'", One = "!", Two = "\"", Four = "$", Five = "%", Six = "&", Seven = "/", Eight = "(", Nine = ")", Zero = "=" }
local QWERTZ = layoutOf(qwertzTyped, qwertzShifted, codes)

