T.section("island_state: lyric height")
local function one()
	return 1
end
local function two()
	return 2
end
local function three()
	return 3
end
T.eq(IS.lyricHeight("", "", one), 32)
T.eq(IS.lyricHeight(nil, nil, one), 32)
T.eq(IS.lyricHeight("a line", "", one), 32)
T.eq(IS.lyricHeight("a line", "next", one), 38)
T.eq(IS.lyricHeight("a long line", "next", two), 52)
T.eq(IS.lyricHeight("a very long line", "next", three), 52)
T.eq(IS.lyricHeight("a long line", "", two), 38)
T.eq(IS.height(32), 170)
T.eq(IS.height(52), 190)

