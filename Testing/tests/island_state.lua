T.section("island_state: stale tokens never mutate state")
s = IS.new()
local first = s:tap(true)
s:finish(first.token)
local second = s:tap(true)
T.ok(not s:finish(first.token))
T.ok(not s:finish(0))
T.ok(not s:finish(nil))
T.eq(s.state, "closing")
T.ok(s:finish(second.token))
T.ok(not s:finish(second.token))
T.eq(s.state, "closed")

T.section("island_state: 50 rapid taps")
s = IS.new()
local tokens = {}
for i = 1, 50 do
	local act = s:tap(true)
	tokens[#tokens + 1] = act.token
end
T.eq(s.state, "closing")
for i = 1, 49 do
	T.ok(not s:finish(tokens[i]), "stale callback " .. i)
end
T.eq(s.state, "closing")
T.ok(s:finish(tokens[50]))
T.eq(s.state, "closed")
for i = 1, 51 do
	local act = s:tap(true)
	if i == 51 then
		T.eq(act.action, "open")
	end
end
T.eq(s.state, "opening")

