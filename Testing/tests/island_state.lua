local IS = loadmodule("Hub/modules/island_state.lua")

T.section("island_state: basic cycle")
local s = IS.new()
T.eq(s.state, "closed")
local a = s:tap(true)
T.eq(a.action, "open")
T.eq(s.state, "opening")
T.ok(s:finish(a.token))
T.eq(s.state, "open")
local b = s:tap(true)
T.eq(b.action, "close")
T.eq(s.state, "closing")
T.ok(s:finish(b.token))
T.eq(s.state, "closed")

T.section("island_state: nothing playing opens home")
s = IS.new()
local h = s:tap(false)
T.eq(h.action, "home")
T.eq(s.state, "closed")
T.eq(s:open(false).action, "none")

T.section("island_state: tap during opening reverses")
s = IS.new()
local o = s:tap(true)
local r = s:tap(true)
T.eq(r.action, "close")
T.eq(s.state, "closing")
T.ok(r.token > o.token)
T.ok(not s:finish(o.token))
T.eq(s.state, "closing")
T.ok(s:finish(r.token))
T.eq(s.state, "closed")

T.section("island_state: tap during closing reopens")
s = IS.new()
local o1 = s:tap(true)
s:finish(o1.token)
local c1 = s:tap(true)
T.eq(s.state, "closing")
local re = s:tap(true)
T.eq(re.action, "open")
T.eq(s.state, "opening")
T.ok(not s:finish(c1.token))
T.eq(s.state, "opening")
T.ok(s:finish(re.token))
T.eq(s.state, "open")

T.section("island_state: tap during closing with no track stays closing")
s = IS.new()
local o2 = s:tap(true)
s:finish(o2.token)
s:tap(true)
local none = s:tap(false)
T.eq(none.action, "none")
T.eq(s.state, "closing")

T.section("island_state: track change during opening swaps content only")
s = IS.new()
local o3 = s:tap(true)
local sw = s:trackChanged()
T.eq(sw.action, "swap")
T.eq(sw.token, o3.token)
T.eq(s.state, "opening")
T.ok(s:finish(o3.token))
T.eq(s.state, "open")
s = IS.new()
T.eq(s:trackChanged().action, "none")

T.section("island_state: track lost while open")
s = IS.new()
local o4 = s:tap(true)
s:finish(o4.token)
local lost = s:sync(false)
T.eq(lost.action, "close")
T.eq(s.state, "closing")
T.ok(s:finish(lost.token))
T.eq(s.state, "closed")
T.eq(s:sync(false).action, "none")
T.eq(s:sync(true).action, "none")

T.section("island_state: hub hidden while opening")
